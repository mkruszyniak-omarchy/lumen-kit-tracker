#!/usr/bin/env python3
"""Generate the KIT L2 badges using original 5x7 lettering, no external packages."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GLYPHS = (
    ("10001", "10010", "10100", "11000", "10100", "10010", "10001"),
    ("11111", "00100", "00100", "00100", "00100", "00100", "11111"),
    ("11111", "00100", "00100", "00100", "00100", "00100", "00100"),
)

for label, width, height, scale in (("mini", 80, 28, 2), ("med", 108, 40, 3)):
    name = f"kit_{label}_{width}x{height}_L2"
    pixels = []
    text_width = 17 * scale
    left, top = (width - text_width) // 2, (height - 7 * scale) // 2
    radius = height / 2
    for y in range(height):
        for x in range(width):
            coverage = 0
            for sy in range(4):
                for sx in range(4):
                    px, py = x + (sx + .5) / 4, y + (sy + .5) / 4
                    cx = min(max(px, radius), width - radius)
                    coverage += (px - cx) ** 2 + (py - radius) ** 2 <= radius ** 2
            value = round(coverage * 3 / 16)
            gx, gy = (x - left) // scale, (y - top) // scale
            if 0 <= gx < 17 and 0 <= gy < 7:
                letter, col = divmod(gx, 6)
                if col < 5 and GLYPHS[letter][gy][col] == "1":
                    value = 0
            pixels.append(value)
    data = [sum(pixels[i + j] << (6 - 2 * j) for j in range(4))
            for i in range(0, len(pixels), 4)]
    rows = ["    " + ", ".join(f"0x{x:02X}" for x in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    (ROOT / "core/libs/images" / f"{name}.h").write_text(
        "// Generated by tools/drum-kit/generate_icons.py; FT812 L2, MSB first.\n"
        f"const uint8_t {name}[{len(data)}] = {{\n" + "\n".join(rows) + "\n};\n")
